const assert=require('node:assert/strict');
const {estimate,duration,step}=require('../tools/generator-timing.js');
const start=Date.parse('2026-11-06T08:00:00Z')/1000;
const job={id:'test',created_at:'2026-11-06T08:00:00Z',updated_at:'2026-11-06T08:03:00Z',status:'running',step:'summarize',events:[{step:'summarize',status:'started',at:'2026-11-06T08:01:00Z'}],config:{pages:12,review_passes:2,summary_model:'openai/gpt-6-luna',draft_model:'openai/gpt-6-luna',polish_model:'openai/gpt-6-luna'},source_metrics:{summary_chunks:8}};
assert.equal(estimate(null),null);
assert.equal(duration(3661),'1h 01m 01s');assert.equal(duration(-10),'0m 00s');assert.equal(duration(NaN),'0m 00s');
const normal=estimate(job,start+180);
assert.equal(normal.elapsed,180);assert.equal(normal.kind,'estimate');assert(normal.low>0 && normal.high>normal.low);
assert(estimate({...job,source_metrics:{summary_chunks:47}},start+180).high>normal.high);
assert(estimate({...job,config:{...job.config,review_passes:4}},start+180).high>normal.high);
assert(estimate({...job,step:'polish'},start+180).high<normal.high);
assert.equal(estimate({...job,status:'ready'},start+900).elapsed,180);
assert.equal(estimate({...job,status:'failed'},start+900).kind,'stopped');
assert.equal(estimate(job,start+900).overTarget,true);
const queued=estimate({...job,status:'queued',batch_wait:{expires_at:start+86400}},start+180);
assert.equal(queued.kind,'batch');assert.equal(queued.deadline,start+86400);assert.equal(queued.high,undefined);
assert.equal(estimate({...job,config:{summary_model:'openai/gpt-6-luna:batch'}},start+180).kind,'batch');
assert.equal(estimate({...job,worker_online:false},start+180).kind,'offline');
assert.equal(estimate({...job,config:{...job.config,summary_service:'flex'}},start+180).kind,'flex');
assert.equal(estimate({...job,config:{...job.config,provider:'databricks',summary_service:'flex'}},start+180).kind,'estimate');
console.log('Timing checks passed: persisted elapsed time, frozen completion, progress estimates, Batch uncertainty and Flex queue caveats.');
const progressJob={...job,step_progress:{step:'summarize',completed:3,total:12,unit:'requests'}};
assert.equal(step(progressJob,'summarize',start+180).elapsed,120);
assert.equal(step(progressJob,'summarize',start+180).percentage,25);
assert.equal(step({...job,step_progress:{}},'summarize',start+180).percentage,null);
const finishedJob={...job,status:'ready',events:[{step:'review',status:'started',at:'2026-11-06T08:00:00Z'},{step:'review',status:'complete',at:'2026-11-06T08:00:20Z'},{step:'review',status:'started',at:'2026-11-06T08:01:00Z'},{step:'review',status:'complete',at:'2026-11-06T08:01:30Z'}]};
assert.equal(step(finishedJob,'review',start+500).elapsed,50);assert.equal(step(finishedJob,'review',start+500).percentage,100);
assert.equal(step({...progressJob,step_progress:{step:'summarize',completed:99,total:12}},'summarize',start+180).percentage,100);
console.log('Step meters use persisted request counts and exact elapsed event times, including repeated review passes.');

const {overall}=require('../tools/generator-timing.js');
assert.equal(overall({status:'idle'}),0);
assert.equal(overall({...job,status:'ready'}),100);
assert.equal(overall({...job,status:'needs_review'}),100);
assert.equal(overall({...job,step:'draft',events:[],step_progress:{step:'draft',completed:1,total:2}}),29);
assert.equal(overall({...job,status:'failed',step:'draft',events:[],step_progress:{step:'draft',completed:1,total:2}}),29);
assert.equal(overall({...job,step:'review',events:['collect','summarize','outline','draft','review','rewrite'].map(step=>({step,status:'complete'}))}),50);
assert.ok(overall({...job,step:'deliver'})<100);
console.log('Overall percentage uses completed workflow stages and known request counts; 100% is reserved for completion.');
