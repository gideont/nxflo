const assert=require('node:assert/strict');
const {estimate,rate}=require('../tools/generator-cost.js');
const prices={models:{test:{input:1,output:2,tiers:[]},free:{input:0,output:0}}};
const config={summary_model:'test',draft_model:'test',polish_model:'test',length_mode:'content',cost_pages:12,review_passes:3,web_search:false,documents:[],youtube:''};
const one=estimate(config,prices,1),two=estimate(config,prices,2),three=estimate(config,prices,3);
assert.ok(Math.abs(one.total-.1243)<1e-9);
assert.ok(Math.abs(three.total-.2475)<1e-9);
assert.ok(one.total<two.total && two.total<three.total);
assert.ok(Math.abs(two.total-one.total-(three.total-two.total))<1e-9);
assert.equal(three.rows.reduce((sum,row)=>sum+row.cost,0),three.total);
assert.equal(estimate({...config,summary_model:'unknown'},prices),null);
assert.equal(estimate({...config,summary_model:'__proto__'},prices),null);
assert.equal(estimate({...config,cost_pages:0},prices),null);
assert.equal(estimate(config,prices,0),null);
assert.equal(estimate({...config,summary_model:'free',draft_model:'free',polish_model:'free'},prices).total,0);
assert.equal(estimate({...config,documents:[{text:'abcdefghijklmnop'}]},prices).sourceTokens,4);
assert.equal(estimate({...config,youtube:'https://youtu.be/abcdefghijk'},prices).sourceTokens,6000);
assert.equal(estimate({...config,length_mode:'target',pages:20,cost_pages:1},prices).pages,20);
assert.deepEqual(rate({input:1,output:2,tiers:[{min_prompt_tokens:2000,prompt:'.000003',completion:'.000005'}]},2000),{input:3,output:5});
assert.ok(Math.abs(estimate({...config,summary_service:'flex',draft_service:'flex',polish_service:'flex'},prices).total-three.total/2)<1e-9);
assert.ok(estimate({...config,revision_parent:'existing-document',feedback:'Expand the recommendations.'},prices).total>three.total);
const researchPrices={models:{...prices.models,'openai/gpt-6-luna':{input:.1,output:.5}}};
const web=estimate({...config,web_search:true,web_budget_usd:.3},researchPrices);
assert.ok(Math.abs(web.rows.find(row=>row.stage.startsWith('Web research')).cost-.00205)<1e-9);
assert.equal(estimate({...config,web_search:true,web_budget_usd:0},researchPrices).total,three.total);
const observed=estimate({...config,web_search:true},researchPrices,3,{source_characters:645789,summary_chunks:47,web_cost:.701728375,web_cost_known:true});
assert.equal(observed.sourceTokens,Math.ceil(645789/4));assert.equal(observed.rows.at(-1).cost,.701728375);assert.ok(observed.total>.701728375);
console.log('Cost calculator checks passed: exact arithmetic, per-pass savings, source assumptions, missing prices, free models and long-context tiers.');

const intent=estimate({...config,document_intent:'product_concept',topic:'Investment and financial decision simulator'},prices);
assert.ok(intent.total>three.total);
assert.ok(intent.rows.some(row=>row.stage==='Extract author intent'));
assert.ok(intent.rows.some(row=>row.stage==='Publication quality gate'));
assert.ok(intent.rows.some(row=>row.stage==='Plan hypothetical scenario inputs'));
assert.ok(intent.rows.some(row=>row.stage==='Fidelity repair allowance'));
